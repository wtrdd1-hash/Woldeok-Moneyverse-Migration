/**
 * Five-locale copy for the /bank client components. Korean is the carried-over product copy and is
 * kept byte-for-byte; the other columns translate it. `{name}` slots are filled after picking, so
 * amounts keep their own formatting (groupDigits) instead of being re-rendered per locale.
 */

/** Fills `{name}` slots in a picked copy string; the values themselves are never translated. */
export function fill(text: string, values: Readonly<Record<string, string>>): string {
  return text.replace(/\{(\w+)\}/g, (slot, name: string) => values[name] ?? slot);
}

